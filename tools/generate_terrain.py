"""Generate both terrain skins from identical periodic contour geometry.

Only the stroke palette and group opacity differ between themes. Regenerate with
python3 tools/generate_terrain.py after editing the shared map geometry below.
"""
from pathlib import Path
from math import sin, cos, pi

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT, STEP = 1600, 1000, 10


def elevation(x, y):
    u, v = 2 * pi * x / WIDTH, 2 * pi * y / HEIGHT
    return (sin(u + 0.55 * sin(v)) + 0.65 * cos(v + 0.7 * cos(u))
            + 0.32 * sin(2 * u - v) + 0.18 * cos(u + 3 * v))


def contours():
    paths = []
    for level_index in range(25):
        level = -2.16 + level_index * 0.18
        segments = []
        for y in range(0, HEIGHT, STEP):
            for x in range(0, WIDTH, STEP):
                corners = [(x, y), (x + STEP, y),
                           (x + STEP, y + STEP), (x, y + STEP)]
                values = [elevation(*point) for point in corners]
                crossings = []
                for i in range(4):
                    j = (i + 1) % 4
                    a, b = values[i], values[j]
                    if (a < level) == (b < level):
                        continue
                    t = (level - a) / (b - a)
                    crossings.append((corners[i][0] + t * (corners[j][0] - corners[i][0]),
                                      corners[i][1] + t * (corners[j][1] - corners[i][1])))
                for i in range(0, len(crossings), 2):
                    a, b = crossings[i:i + 2]
                    segments.append(f'M{a[0]:.2f},{a[1]:.2f}L{b[0]:.2f},{b[1]:.2f}')
        paths.append(f'<path stroke-width="{1.4 if level_index % 4 == 0 else 0.85}" d="{"".join(segments)}"/>')
    return '\n'.join(paths)


CONTOURS = contours()
GRID = '<path d="' + ''.join(f'M{x} 0V1000' for x in range(0, WIDTH, 200)) + ''.join(f'M0 {y}H1600' for y in range(0, HEIGHT, 200)) + '"/>'
SURVEY = ''.join(f'<path d="M{x-7} {y}h14M{x} {y-7}v14"/><circle cx="{x}" cy="{y}" r="3"/>'
                 for x, y in [(200, 200), (1200, 400), (600, 800), (1400, 800)])
SURVEY += '<path stroke-dasharray="4 9" d="M1040 160l280 70-40 210-240-35z"/>'

for theme, color, contour_opacity, grid_opacity, survey_opacity in [
    ('dark', '#8caee0', '.28', '.065', '.28'),
    ('light', '#1451a4', '.20', '.055', '.23'),
]:
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="1000" viewBox="0 0 1600 1000" fill="none" stroke="{color}">
<!-- Generated by tools/generate_terrain.py; shared geometry, theme strokes only. -->
<defs><radialGradient id="quiet"><stop stop-color="white" stop-opacity=".40"/><stop offset="1" stop-color="white" stop-opacity="1"/></radialGradient><mask id="terrain"><path fill="url(#quiet)" stroke="none" d="M0 0h1600v1000H0z"/></mask></defs>
<g mask="url(#terrain)">
<g opacity="{grid_opacity}" stroke-width=".6">{GRID}</g>
<g opacity="{contour_opacity}" stroke-linecap="round" stroke-linejoin="round">{CONTOURS}</g>
<g opacity="{survey_opacity}" stroke-width=".8">{SURVEY}</g>
</g></svg>
'''
    (ROOT / f'assets/terrain/contours-{theme}.svg').write_text(svg)
